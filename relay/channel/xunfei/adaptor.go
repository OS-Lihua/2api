func (a *Provider) RequestURL(metadata channel.ProviderMetadata) (string, error) {
	info := metadata.ProviderRequest()
	parts := strings.Split(info.ApiKey, "|")
	if len(parts) != 3 {
		return "", errors.New("invalid auth")
	}
	version := ""
	if requestURL, err := url.Parse(info.RequestURLPath); err == nil {
		version = requestURL.Query().Get("api-version")
	}
	if version == "" {
		modelParts := strings.Split(info.UpstreamModelName, "-")
		if len(modelParts) == 2 {
			version = modelParts[1]
		}
	}
	if version == "" {
		version = info.ApiVersion
	}
	if version == "" {
		version = "v1.1"
	}
	endpoint := fmt.Sprintf("wss://spark-api.xf-yun.com/%s/chat", version)
	if _, err := url.Parse(endpoint); err != nil {
		return "", errors.New("invalid Xunfei API version")
	}
	return a.authURL(endpoint, parts[2], parts[1]), nil
}

